create table if not exists public.users (
  id text primary key,
  email text not null unique,
  display_name text not null,
  avatar_url text,
  timezone text not null default 'Asia/Taipei',
  last_login_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.checkins (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  owner_email text not null,
  entry_date text not null,
  metrics text not null,
  sleep integer not null default 0,
  stress integer not null default 0,
  note text not null default '',
  whole_routine text not null default '',
  left_routine text not null default '',
  right_routine text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, entry_date)
);

create table if not exists public.face_photos (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(id) on delete cascade,
  owner_email text not null,
  entry_date text not null,
  angle text not null check (angle in ('front', 'left', 'right')),
  object_key text not null unique,
  content_type text not null,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;
alter table public.checkins enable row level security;
alter table public.face_photos enable row level security;

drop policy if exists users_select_own on public.users;
drop policy if exists users_insert_own on public.users;
drop policy if exists users_update_own on public.users;
create policy users_select_own on public.users for select using (auth.uid()::text = id);
create policy users_insert_own on public.users for insert with check (auth.uid()::text = id);
create policy users_update_own on public.users for update using (auth.uid()::text = id) with check (auth.uid()::text = id);

